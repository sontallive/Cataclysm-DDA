#include "../../src/sdl_touch_shortcuts.cpp"
#include <cassert>
#include <cstdio>
int main()
{
    using namespace sdl_touch_shortcuts;
    std::optional<input_event> selected;
    SDL_Event e{};
    e.type = SDL_MOUSEBUTTONDOWN;
    e.button.button = SDL_BUTTON_LEFT;
    e.button.x = 20;
    e.button.y = 770;
    assert( !enabled() );
    assert( !handle_event( e, selected ) );
    enable();
    window_width = 1280;
    window_height = 800;
    input_event key( 'a', input_event_t::keyboard_code );
    key.modifiers.insert( keymod_t::shift );
    shortcuts.update( "probe", {{key, "A", "Action"}} );
    shortcuts.resize( 1280, 800, 56 );
    assert( handle_event( e, selected ) );
    assert( !selected );
    e.type = SDL_MOUSEBUTTONUP;
    assert( handle_event( e, selected ) );
    assert( selected && *selected == key );
    selected.reset();
    assert( handle_event( e, selected ) );
    assert( !selected );
    e.type = SDL_FINGERDOWN;
    e.tfinger.fingerId = 9042;
    e.tfinger.x = 20.0f / 1280;
    e.tfinger.y = 770.0f / 800;
    assert( handle_event( e, selected ) );
    e.type = SDL_FINGERUP;
    assert( handle_event( e, selected ) );
    assert( selected && *selected == key );
    selected.reset();
    e = {};
    e.type = SDL_MOUSEBUTTONDOWN;
    e.button.which = SDL_TOUCH_MOUSEID;
    e.button.button = SDL_BUTTON_LEFT;
    e.button.x = 20;
    e.button.y = 770;
    assert( handle_event( e, selected ) );
    e.type = SDL_MOUSEBUTTONUP;
    assert( handle_event( e, selected ) );
    assert( !selected );
    e.button.which = 1;
    e.type = SDL_MOUSEBUTTONDOWN;
    assert( handle_event( e, selected ) );
    SDL_Event focus{};
    focus.type = SDL_WINDOWEVENT;
    focus.window.event = SDL_WINDOWEVENT_FOCUS_LOST;
    handle_event( focus, selected );
    focus.window.event = SDL_WINDOWEVENT_FOCUS_GAINED;
    handle_event( focus, selected );
    e.type = SDL_MOUSEBUTTONUP;
    e.button.y = 500;
    assert( handle_event( e, selected ) );
    assert( !selected );
    e.type = SDL_MOUSEBUTTONDOWN;
    e.button.y = 770;
    assert( handle_event( e, selected ) );
    shortcuts.update( "new dialog", {{key, "A", "Action"}} );
    e.type = SDL_MOUSEBUTTONUP;
    e.button.y = 500;
    assert( handle_event( e, selected ) );
    assert( !selected );
    e.type = SDL_MOUSEBUTTONDOWN;
    e.button.y = 770;
    assert( handle_event( e, selected ) );
    e.type = SDL_MOUSEMOTION;
    e.motion.x = 20;
    e.motion.y = 500;
    assert( handle_event( e, selected ) );
    e.type = SDL_MOUSEBUTTONUP;
    e.button.button = SDL_BUTTON_LEFT;
    e.button.x = 20;
    e.button.y = 500;
    assert( handle_event( e, selected ) );
    assert( !selected );
    puts( "SDL routing: opt-in, modified clicks, raw touch, synthetic mouse deduplication, focus and context cancellation passed" );
}
